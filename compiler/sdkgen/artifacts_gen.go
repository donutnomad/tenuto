package sdkgen

import (
	"fmt"
	"go/parser"
	"go/token"
	"path/filepath"
)

// embeddedArtifactsFile 渲染随二进制发布的 `zz_<pkg>_artifacts_gen.go`。
//
// 只打包运行必需的 workflow.json：WLang 程序就在它的 program 字段里，二进制不需要源码目录或其余 JSON。
// 内容只依赖包名，两次生成逐字节相同。
func embeddedArtifactsFile(dir, packageName string) GeneratedFile {
	return GeneratedFile{
		Path:    filepath.Join(dir, "zz_"+packageName+"_artifacts_gen.go"),
		Content: renderEmbeddedArtifacts(packageName),
	}
}

func renderEmbeddedArtifacts(packageName string) []byte {
	return []byte(fmt.Sprintf(`// Code generated by tenuto-workflow-gen. DO NOT EDIT.

package %s

import (
	"embed"

	"github.com/donutnomad/tenuto/sdk/registration"
)

// tenutoWorkflowArtifacts 把同目录的 workflow.json 打进二进制；运行期不需要源码或 JSON 文件。
//
//go:embed workflow.json
var tenutoWorkflowArtifacts embed.FS

// WorkflowDefinition 返回本包随二进制发布的 Workflow 定义。
// worker.Options.Workflows（sdk/worker）引用它即可在 Worker 启动时自动登记。
func WorkflowDefinition() registration.Definition {
	return registration.Definition{FS: tenutoWorkflowArtifacts}
}
`, packageName))
}

// packageClauseName 读取源码的包名。
func packageClauseName(src []byte) (string, error) {
	file, err := parser.ParseFile(token.NewFileSet(), "source.go", src, parser.PackageClauseOnly)
	if err != nil {
		return "", err
	}
	return file.Name.Name, nil
}
